/**
 * The catalogue for a locale, with English filled in behind it. Doing the merge
 * once per language change (rather than per lookup) keeps `t()` a plain object
 * read.
 */
export function catalogFor(code) {
  return code === 'en' ? en : { ...en, ...(translations[code] || {}) }
}

